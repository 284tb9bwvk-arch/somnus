  function updateSlider(value) {
    // 1. Движение вертикального индикатора
    indicator.style.left = `${value}%`;

    // 2. Расчет времени (0% = 06:00, 100% = 06:00 след. дня)
    const totalHoursPassed = (value / 100) * 24;
    let currentHour = Math.floor(6 + totalHoursPassed);
    let currentMinute = Math.floor((totalHoursPassed % 1) * 60);
    
    if (currentHour >= 24) currentHour -= 24;
    
    const formatTime = (h, m) => `${h.toString().padStart(2, '0')}:${m.toString().padStart(2, '0')}`;
    timeLabel.textContent = formatTime(currentHour, currentMinute);

    // 3. Определение фазы и обновление текста
    const currentPhase = phases.find(p => value <= p.endPercent) || phases[phases.length - 1];
    
    // Предотвращаем лишние перерисовки DOM
    if (uiCategory.textContent !== currentPhase.category) {
      uiCategory.textContent = currentPhase.category;
      uiTitle.textContent = currentPhase.title;
      uiDesc.textContent = currentPhase.desc;
      uiMelatonin.textContent = currentPhase.mel;
      uiCortisol.textContent = currentPhase.cor;
    }
  }
