    const countEl = document.getElementById('library-count');
    let searchQuery = '';

    // 3. РЕНДЕР КАРТОЧЕК
    const renderCards = (data) => {
        grid.innerHTML = '';
        
        if (data.length === 0) {
            emptyState.classList.remove('hidden');
            return;
        }
        
        emptyState.classList.add('hidden');
        const fragment = document.createDocumentFragment();
        
        data.forEach(item => {
            const card = document.createElement('article');
            card.className = 'science-card';
            card.setAttribute('tabindex', '0');
            card.setAttribute('role', 'button');
            card.setAttribute('aria-label', `Открыть исследование: ${item.title}`);
            
            const tagsHtml = item.tags.map(tag => `<span class="card-tag">${tag}</span>`).join('');
            
            card.innerHTML = `
                <div class="card-top">
                    <span class="card-category">${item.categoryLabel}</span>
                    <h3 class="card-title">${item.title}</h3>
                    <p class="card-meta">${item.authors} &middot; ${item.year} &middot; ${item.journal}</p>
                    <p class="card-summary">${item.summary}</p>
                    <div class="card-tags">${tagsHtml}</div>
                </div>
                <div class="card-action">
                    <span class="card-read-more">Читать подробнее &rarr;</span>
                    <span class="card-read-time">${item.readingTime}</span>
                </div>
            `;
            
            card.addEventListener('click', () => openModal(item));
            card.addEventListener('keydown', (e) => {
                if (e.key === 'Enter' || e.key === ' ') {
                    e.preventDefault();
                    openModal(item);
                }
            });
            
            fragment.appendChild(card);
        });
        
        grid.appendChild(fragment);
    };

