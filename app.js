/**
 * Архитектура JavaScript
 * Проект: Somnus (Наука о сне)
 * Текущая сборка: Включает Интерактивную спальню и Биохимию суток
 */

document.addEventListener('DOMContentLoaded', () => {
    const heroSection = document.getElementById('somnus-hero-section');
    if (!heroSection) return;

    // Проверка поддержки точного курсора и настроек ОС пользователя
    const isFinePointer = window.matchMedia('(pointer: fine)').matches;
    const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

    if (isFinePointer && !prefersReducedMotion) {
        let ticking = false;

        heroSection.addEventListener('mousemove', (e) => {
            if (!ticking) {
                window.requestAnimationFrame(() => {
                    const rect = heroSection.getBoundingClientRect();
                    // Нормализация координат от -1 до 1 относительно центра
                    const x = ((e.clientX - rect.left) / rect.width) * 2 - 1;
                    const y = ((e.clientY - rect.top) / rect.height) * 2 - 1;
                    
                    // Запись в CSS переменные
                    heroSection.style.setProperty('--somnus-mx', x.toFixed(3));
                    heroSection.style.setProperty('--somnus-my', y.toFixed(3));
                    
                    ticking = false;
                });
                ticking = true;
            }
        });

        // Плавный возврат в центр при уходе мыши
        heroSection.addEventListener('mouseleave', () => {
            heroSection.style.setProperty('--somnus-mx', 0);
            heroSection.style.setProperty('--somnus-my', 0);
        });
    }
});
        
