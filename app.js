function initSomnusHeader() {
    const header = document.getElementById('somnus-header');
    const mobileToggle = document.getElementById('somnus-mobile-toggle');
    const nav = document.getElementById('somnus-nav');
    const links = document.querySelectorAll('.somnus-header__link');
    const sections = document.querySelectorAll('section[id]'); // Все секции

    if (!header) return; // Защита от ошибок, если скрипт загружен не там

    // --- 1. Логика скролла (Glass-effect) ---
    const handleScroll = () => {
        if (window.scrollY > 20) {
            header.classList.add('is-scrolled');
        } else {
            header.classList.remove('is-scrolled');
        }
    };
    window.addEventListener('scroll', handleScroll, { passive: true });
    handleScroll(); // Проверка при загрузке

    // --- 2. Логика мобильного меню ---
    if (mobileToggle && nav) {
        const toggleMenu = (forceClose = false) => {
            const isOpen = nav.classList.contains('somnus-header__nav--open');
            const willOpen = forceClose ? false : !isOpen;

            if (willOpen) {
                nav.classList.add('somnus-header__nav--open');
                mobileToggle.setAttribute('aria-expanded', 'true');
                mobileToggle.setAttribute('aria-label', 'Закрыть меню');
                mobileToggle.classList.add('is-active'); // Если у вас есть анимация крестика
                document.body.style.overflow = 'hidden'; // Блокировка скролла
            } else {
                nav.classList.remove('somnus-header__nav--open');
                mobileToggle.setAttribute('aria-expanded', 'false');
                mobileToggle.setAttribute('aria-label', 'Открыть меню');
                mobileToggle.classList.remove('is-active');
                document.body.style.overflow = '';
            }
        };

        // Клик по бургеру
        mobileToggle.addEventListener('click', () => toggleMenu());

        // Закрытие при клике на ЛЮБУЮ навигационную ссылку внутри меню
        // (обычные пункты .somnus-header__link И пункты выпадающего списка .dropdown-item)
        const allNavLinks = nav.querySelectorAll('a');
        allNavLinks.forEach(link => {
            link.addEventListener('click', () => toggleMenu(true));
        });

        // Закрытие по клавише Escape
        document.addEventListener('keydown', (e) => {
            if (e.key === 'Escape' && nav.classList.contains('somnus-header__nav--open')) {
                toggleMenu(true);
            }
        });
    }

    // --- 3. Логика Active State (Intersection Observer) ---
    if (links.length > 0 && sections.length > 0) {
        // Настройка: секция становится активной только когда пересекает середину экрана
        const observerOptions = {
            root: null,
            rootMargin: '-50% 0px -50% 0px', 
            threshold: 0
        };

        // Секции, которые визуально относятся к одному пункту меню "Интерактив"
        const interactiveGroup = ['interactive-bedroom', 'biochemistry-section', 'neuro-breathing-module'];

        const observerCallback = (entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    const activeId = entry.target.id;
                    
                    // Снимаем active со всех ссылок
                    links.forEach(link => link.classList.remove('somnus-header__link--active'));
                    
                    // Спальня/Биохимия/Дыхание вместе подсвечивают пункт "Интерактив"
                    const targetHref = interactiveGroup.includes(activeId) ? '#interactive-bedroom' : `#${activeId}`;
                    const activeLink = document.querySelector(`.somnus-header__link[href="${targetHref}"]`);
                    if (activeLink) {
                        activeLink.classList.add('somnus-header__link--active');
                    }
                }
            });
        };

        const observer = new IntersectionObserver(observerCallback, observerOptions);
        sections.forEach(section => observer.observe(section));
    }
}




