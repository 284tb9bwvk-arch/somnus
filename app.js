            text.textContent = name;
            
            // Настраиваем визуал под фазу
            circle.style.transitionDuration = `${transitionSec}s`;
            circle.style.transform = `scale(${scale})`;
            circle.style.borderColor = color;
            circle.style.boxShadow = `0 0 30px ${color}40`;
            
