document.addEventListener('DOMContentLoaded', () => {
    // 1. ЛОГИКА СВОРАЧИВАНИЯ ИССЛЕДОВАНИЙ
    const toggleBtn = document.getElementById('toggle-grid-btn');
    const scienceGrid = document.getElementById('science-grid');

    if (toggleBtn && scienceGrid) {
        toggleBtn.addEventListener('click', () => {
            scienceGrid.classList.toggle('collapsed');
            
            if (scienceGrid.classList.contains('collapsed')) {
                toggleBtn.textContent = 'Развернуть исследования';
                // Опционально: прокрутка к началу секции при сворачивании, чтобы не потерять контекст
                document.getElementById('science').scrollIntoView({ behavior: 'smooth', block: 'start' });
            } else {
                toggleBtn.textContent = 'Свернуть исследования';
            }
        });
    }

    // ==========================================================================
// ПОДСВЕТКА АКТИВНОГО РАЗДЕЛА (УСТОЙЧИВАЯ К ДИНАМИЧЕСКОЙ ВЫСОТЕ)
// ==========================================================================
const sections = document.querySelectorAll('section[id]');
const navLinks = document.querySelectorAll('nav a[href^="#"]');

if (sections.length > 0 && navLinks.length > 0) {
    const updateActiveNav = () => {
        // Линия считывания: 25% от верха экрана (с учетом фиксированной шапки)
        const scrollPosition = window.scrollY + (window.innerHeight * 0.25);

        let currentId = '';

        sections.forEach(section => {
            const sectionTop = section.offsetTop;
            const sectionHeight = section.offsetHeight;

            // Проверяем, находится ли точка скролла внутри физических границ секции
            if (scrollPosition >= sectionTop && scrollPosition < sectionTop + sectionHeight) {
                currentId = section.getAttribute('id');
            }
        });

        // Если скролл дошел до самого низа страницы — подсвечиваем последнюю секцию
        if ((window.innerHeight + window.scrollY) >= document.body.offsetHeight - 50) {
            currentId = sections[sections.length - 1].getAttribute('id');
        }

        if (currentId) {
            navLinks.forEach(link => {
                const href = link.getAttribute('href');
                const isMatch = href === `#${currentId}` || href.endsWith(`#${currentId}`);
                
                // Добавляем оба класса для гарантированного срабатывания ваших стилей
                if (isMatch) {
                    link.classList.add('active-section', 'active');
                } else {
                    link.classList.remove('active-section', 'active');
                }
            });
        }
    };

    // Оптимизированный слушатель скролла (без лагов и подвисаний)
    let isTicking = false;
    window.addEventListener('scroll', () => {
        if (!isTicking) {
            window.requestAnimationFrame(() => {
                updateActiveNav();
                isTicking = false;
            });
            isTicking = true;
        }
    });

    // Мгновенный пересчет при кликах (разворачивание статей/фильтры) и изменении размера окна
    document.addEventListener('click', () => setTimeout(updateActiveNav, 120));
    window.addEventListener('resize', updateActiveNav);

    // Первичная инициализация при загрузке
    updateActiveNav();
}
    // 1. ПРОВЕРКА ИНИЦИАЛИЗАЦИИ
    const librarySection = document.getElementById('library');
    // Если мы не на странице с библиотекой или данные не загрузились — прерываем выполнение
    if (!librarySection || typeof scienceData === 'undefined') return;

    // 2. DOM ЭЛЕМЕНТЫ
    const grid = document.getElementById('science-grid');
    const emptyState = document.getElementById('science-empty');
    const searchInput = document.getElementById('scienceSearch');
    const filterBtns = document.querySelectorAll('.filter-btn');
    const modal = document.getElementById('science-modal');
    const modalCloseBtns = document.querySelectorAll('[data-close-modal]');
    if (modal) document.body.appendChild(modal);
    
    let currentFilter = 'all';
    let searchQuery = '';

    // 3. РЕНДЕР КАРТОЧЕК
    const renderCards = (data) => {
        grid.innerHTML = '';
        
        if (data.length === 0) {
            emptyState.classList.remove('hidden');
            return;
        }
        
        emptyState.classList.add('hidden');
        const fragment = document.createDocumentFragment();
        
        data.forEach(item => {
            const card = document.createElement('article');
            card.className = 'science-card';
            card.setAttribute('tabindex', '0');
            card.setAttribute('role', 'button');
            card.setAttribute('aria-label', `Открыть исследование: ${item.title}`);
            
            const tagsHtml = item.tags.map(tag => `<span class="card-tag">${tag}</span>`).join('');
            
            card.innerHTML = `
                <div class="card-top">
                    <span class="card-category">${item.categoryLabel}</span>
                    <h3 class="card-title">${item.title}</h3>
                    <p class="card-meta">${item.authors} &middot; ${item.year} &middot; ${item.journal}</p>
                    <p class="card-summary">${item.summary}</p>
                    <div class="card-tags">${tagsHtml}</div>
                </div>
                <div class="card-action">
                    <span class="card-read-more">Читать подробнее &rarr;</span>
                    <span class="card-read-time">${item.readingTime}</span>
                </div>
            `;
            
            card.addEventListener('click', () => openModal(item));
            card.addEventListener('keydown', (e) => {
                if (e.key === 'Enter' || e.key === ' ') {
                    e.preventDefault();
                    openModal(item);
                }
            });
            
            fragment.appendChild(card);
        });
        
        grid.appendChild(fragment);
    };

    // 4. ЛОГИКА ФИЛЬТРАЦИИ И ПОИСКА
    const filterData = () => {
        const query = searchQuery.toLowerCase().trim();
        
        const filtered = scienceData.filter(item => {
            const matchesCategory = currentFilter === 'all' || item.category === currentFilter;
            if (!matchesCategory) return false;
            if (!query) return true;
            
            const searchableText = `
                ${item.title} 
                ${item.authors} 
                ${item.journal} 
                ${item.tags.join(' ')} 
                ${item.summary}
            `.toLowerCase();
            
            return searchableText.includes(query);
        });
        
        renderCards(filtered);
    };

    // 5. ОБРАБОТЧИКИ УПРАВЛЕНИЯ
    filterBtns.forEach(btn => {
        btn.addEventListener('click', (e) => {
            filterBtns.forEach(b => b.classList.remove('active'));
            e.target.classList.add('active');
            currentFilter = e.target.dataset.filter;
            filterData();
        });
    });

    // Debounce для поиска (предотвращает лаги при быстром вводе)
    let searchTimeout;
    searchInput.addEventListener('input', (e) => {
        clearTimeout(searchTimeout);
        searchTimeout = setTimeout(() => {
            searchQuery = e.target.value;
            filterData();
        }, 200);
    });

    // 6. УПРАВЛЕНИЕ МОДАЛЬНЫМ ОКНОМ
    let previouslyFocusedElement = null;

    const openModal = (item) => {
        previouslyFocusedElement = document.activeElement;
        
        // Инъекция данных
        document.getElementById('modal-journal').textContent = `${item.journal}, ${item.year}`;
        document.getElementById('modal-title').textContent = item.title;
        document.getElementById('modal-authors').textContent = item.authors;
        document.getElementById('modal-design').textContent = item.whatStudied;
        document.getElementById('modal-findings').textContent = item.findings;
        document.getElementById('modal-importance').textContent = item.whyItMatters;
        
        const limitationsContainer = document.getElementById('modal-limitations-container');
        if (item.limitations) {
            document.getElementById('modal-limitations').textContent = item.limitations;
            limitationsContainer.style.display = 'block';
        } else {
            limitationsContainer.style.display = 'none';
        }
        
        const sourceLink = document.getElementById('modal-source-link');
        sourceLink.href = item.pubmedUrl || `https://doi.org/${item.doi}`;
        
        // Отображение
        modal.classList.add('active');
        modal.setAttribute('aria-hidden', 'false');
        document.body.style.overflow = 'hidden'; // Блокировка фонового скролла
        
        // Фокус для доступности
        setTimeout(() => modal.querySelector('.modal-close').focus(), 50);
    };

    const closeModal = () => {
        modal.classList.remove('active');
        modal.setAttribute('aria-hidden', 'true');
        document.body.style.overflow = ''; // Возврат скролла
        
        if (previouslyFocusedElement) {
            previouslyFocusedElement.focus();
        }
    };

    modalCloseBtns.forEach(btn => {
        btn.addEventListener('click', closeModal);
    });

    // Закрытие по Escape
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && modal.classList.contains('active')) {
            closeModal();
        }
    });

    // 7. ПЕРВИЧНАЯ ИНИЦИАЛИЗАЦИЯ
    renderCards(scienceData);
});
