    const filterData = () => {
        const query = searchQuery.toLowerCase().trim();
        
        const filtered = scienceData.filter(item => {
            const matchesCategory = currentFilter === 'all' || (currentFilter === 'featured' ? (query !== '' || featuredIds.includes(item.id)) : item.category === currentFilter);
            if (!matchesCategory) return false;
            if (!query) return true;
            
            const searchableText = `
                ${item.title} 
                ${item.authors} 
                ${item.journal} 
                ${item.tags.join(' ')} 
                ${item.summary}
            `.toLowerCase();
            
            return searchableText.includes(query);
        });
        
        renderCards(filtered);
        if (countEl) { const n = filtered.length, m = n % 10, k = n % 100; countEl.textContent = 'Показано ' + n + ' ' + ((m === 1 && k !== 11) ? 'исследование' : (m >= 2 && m <= 4 && (k < 12 || k > 14)) ? 'исследования' : 'исследований') + ' из ' + scienceData.length; }
    };

