document.addEventListener('DOMContentLoaded', () => {
    const siteNav = document.getElementById('siteNav');
    const burgerToggle = document.getElementById('burgerToggle');

    if (siteNav) {
        siteNav.addEventListener('click', (e) => {
            // Находим ссылку, по которой кликнули (или её родителя)
            const link = e.target.closest('a');
            if (!link) return;

            const href = link.getAttribute('href');

            if (href && href.startsWith('#')) {
                const target = document.querySelector(href);
                if (target) {
                    e.preventDefault();

                    // 1. Плавный скролл к секции
                    target.scrollIntoView({ behavior: 'smooth', block: 'start' });

                    // 2. Имитируем клик по кнопке бургера, чтобы сработал штатный скрипт закрытия
                    if (burgerToggle && (siteNav.classList.contains('is-open') || siteNav.classList.contains('active') || siteNav.classList.contains('open'))) {
                        burgerToggle.click();
                    } else {
                        // Резервный сброс всех возможных классов
                        siteNav.classList.remove('is-open', 'active', 'open', 'is-active');
                        if (burgerToggle) {
                            burgerToggle.classList.remove('is-open', 'active', 'open', 'is-active');
                        }
                    }
                }
            }
        });
    }
});
